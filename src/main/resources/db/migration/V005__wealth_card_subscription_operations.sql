CREATE TABLE customer_risk_profile (
    id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    risk_level VARCHAR(8) NOT NULL,
    assessed_at DATE NOT NULL,
    valid_until DATE NOT NULL,
    source VARCHAR(40) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_risk_profile_user (user_id),
    CONSTRAINT fk_risk_profile_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT chk_risk_profile_level CHECK (risk_level IN ('R1', 'R2', 'R3', 'R4', 'R5')),
    CONSTRAINT chk_risk_profile_dates CHECK (valid_until >= assessed_at)
) ENGINE=InnoDB;

CREATE TABLE suitability_check (
    id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    product_id CHAR(36) NOT NULL,
    payment_account_id CHAR(36) NOT NULL,
    amount DECIMAL(19,4) NOT NULL,
    currency CHAR(3) NOT NULL,
    user_risk_level VARCHAR(8) NOT NULL,
    product_risk_level VARCHAR(8) NOT NULL,
    product_version BIGINT NOT NULL,
    account_version BIGINT NOT NULL,
    status VARCHAR(24) NOT NULL,
    reason_code VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_suitability_owner_time (user_id, created_at),
    CONSTRAINT fk_suitability_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_suitability_product FOREIGN KEY (product_id) REFERENCES wealth_product(id),
    CONSTRAINT fk_suitability_account FOREIGN KEY (payment_account_id) REFERENCES account(id),
    CONSTRAINT chk_suitability_status CHECK (status IN ('APPROVED', 'DENIED')),
    CONSTRAINT chk_suitability_amount CHECK (amount > 0)
) ENGINE=InnoDB;

CREATE TABLE investment_order (
    id CHAR(36) NOT NULL,
    operation_id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    product_id CHAR(36) NOT NULL,
    payment_account_id CHAR(36) NOT NULL,
    suitability_check_id CHAR(36) NOT NULL,
    amount DECIMAL(19,4) NOT NULL,
    currency CHAR(3) NOT NULL,
    status VARCHAR(24) NOT NULL,
    balance_before DECIMAL(19,4) NOT NULL,
    balance_after DECIMAL(19,4) NOT NULL,
    completed_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_investment_operation (operation_id),
    KEY idx_investment_owner_time (user_id, completed_at),
    CONSTRAINT fk_investment_operation FOREIGN KEY (operation_id) REFERENCES operation_request(id),
    CONSTRAINT fk_investment_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_investment_product FOREIGN KEY (product_id) REFERENCES wealth_product(id),
    CONSTRAINT fk_investment_account FOREIGN KEY (payment_account_id) REFERENCES account(id),
    CONSTRAINT fk_investment_suitability FOREIGN KEY (suitability_check_id) REFERENCES suitability_check(id),
    CONSTRAINT chk_investment_status CHECK (status IN ('SUCCEEDED', 'FAILED')),
    CONSTRAINT chk_investment_amount CHECK (amount > 0)
) ENGINE=InnoDB;

CREATE TABLE wealth_holding (
    id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    product_id CHAR(36) NOT NULL,
    invested_amount DECIMAL(19,4) NOT NULL,
    currency CHAR(3) NOT NULL,
    status VARCHAR(24) NOT NULL,
    opened_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_holding_owner_product (user_id, product_id),
    CONSTRAINT fk_holding_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_holding_product FOREIGN KEY (product_id) REFERENCES wealth_product(id),
    CONSTRAINT chk_holding_status CHECK (status IN ('ACTIVE', 'CLOSED')),
    CONSTRAINT chk_holding_amount CHECK (invested_amount >= 0)
) ENGINE=InnoDB;

CREATE TABLE card_change_history (
    id CHAR(36) NOT NULL,
    operation_id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    card_id CHAR(36) NOT NULL,
    change_type VARCHAR(24) NOT NULL,
    before_state_json LONGTEXT NOT NULL,
    after_state_json LONGTEXT NOT NULL,
    reason_code VARCHAR(64) NOT NULL,
    completed_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_card_change_operation (operation_id),
    KEY idx_card_change_card_time (card_id, completed_at),
    CONSTRAINT fk_card_change_operation FOREIGN KEY (operation_id) REFERENCES operation_request(id),
    CONSTRAINT fk_card_change_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_card_change_card FOREIGN KEY (card_id) REFERENCES bank_card(id),
    CONSTRAINT chk_card_change_type CHECK (change_type IN ('STATUS', 'CONTROLS')),
    CONSTRAINT chk_card_change_before_json CHECK (JSON_VALID(before_state_json)),
    CONSTRAINT chk_card_change_after_json CHECK (JSON_VALID(after_state_json))
) ENGINE=InnoDB;

CREATE TABLE subscription_change_history (
    id CHAR(36) NOT NULL,
    operation_id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    subscription_id CHAR(36) NOT NULL,
    action VARCHAR(24) NOT NULL,
    before_status VARCHAR(24) NOT NULL,
    after_status VARCHAR(24) NOT NULL,
    reason_code VARCHAR(64) NOT NULL,
    effective_at TIMESTAMP(6) NOT NULL,
    completed_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_subscription_change_operation (operation_id),
    KEY idx_subscription_change_time (subscription_id, completed_at),
    CONSTRAINT fk_subscription_change_operation FOREIGN KEY (operation_id) REFERENCES operation_request(id),
    CONSTRAINT fk_subscription_change_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_subscription_change_subscription FOREIGN KEY (subscription_id) REFERENCES subscription(id),
    CONSTRAINT chk_subscription_action CHECK (action IN ('CANCEL')),
    CONSTRAINT chk_subscription_before CHECK (before_status IN ('ACTIVE', 'PAUSED')),
    CONSTRAINT chk_subscription_after CHECK (after_status = 'CANCELLED')
) ENGINE=InnoDB;
