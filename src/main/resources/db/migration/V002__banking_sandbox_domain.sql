CREATE TABLE account (
    id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    account_token VARCHAR(80) NOT NULL,
    account_masked VARCHAR(32) NOT NULL,
    alias VARCHAR(80) NOT NULL,
    account_type VARCHAR(24) NOT NULL,
    currency CHAR(3) NOT NULL,
    ledger_balance DECIMAL(19,4) NOT NULL,
    available_balance DECIMAL(19,4) NOT NULL,
    status VARCHAR(24) NOT NULL,
    daily_transfer_limit DECIMAL(19,4) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_account_token (account_token),
    KEY idx_account_owner_status (user_id, status),
    CONSTRAINT fk_account_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT chk_account_type CHECK (account_type IN ('CHECKING', 'SAVINGS')),
    CONSTRAINT chk_account_status CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    CONSTRAINT chk_account_balance CHECK (ledger_balance >= 0 AND available_balance >= 0)
) ENGINE=InnoDB;

CREATE TABLE bank_card (
    id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    linked_account_id CHAR(36) NOT NULL,
    card_token VARCHAR(80) NOT NULL,
    card_masked VARCHAR(32) NOT NULL,
    card_type VARCHAR(24) NOT NULL,
    status VARCHAR(24) NOT NULL,
    online_enabled BOOLEAN NOT NULL,
    overseas_enabled BOOLEAN NOT NULL,
    single_tx_limit DECIMAL(19,4) NOT NULL,
    daily_limit DECIMAL(19,4) NOT NULL,
    expiry_month CHAR(7) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_bank_card_token (card_token),
    KEY idx_bank_card_owner_status (user_id, status),
    CONSTRAINT fk_bank_card_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_bank_card_account FOREIGN KEY (linked_account_id) REFERENCES account(id),
    CONSTRAINT chk_bank_card_type CHECK (card_type IN ('DEBIT', 'CREDIT')),
    CONSTRAINT chk_bank_card_status CHECK (status IN ('ACTIVE', 'FROZEN', 'LOST', 'CLOSED')),
    CONSTRAINT chk_bank_card_limits CHECK (single_tx_limit >= 0 AND daily_limit >= single_tx_limit)
) ENGINE=InnoDB;

CREATE TABLE payee (
    id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    name VARCHAR(100) NOT NULL,
    bank_name VARCHAR(100) NOT NULL,
    account_token VARCHAR(80) NOT NULL,
    account_masked VARCHAR(32) NOT NULL,
    internal_account_id CHAR(36) NULL,
    currency CHAR(3) NOT NULL,
    status VARCHAR(24) NOT NULL,
    trusted BOOLEAN NOT NULL,
    last_used_at TIMESTAMP(6) NULL,
    created_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_payee_owner_token (user_id, account_token),
    KEY idx_payee_owner_name_status (user_id, name, status),
    CONSTRAINT fk_payee_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_payee_internal_account FOREIGN KEY (internal_account_id) REFERENCES account(id),
    CONSTRAINT chk_payee_status CHECK (status IN ('ACTIVE', 'DISABLED'))
) ENGINE=InnoDB;

CREATE TABLE account_transaction (
    id CHAR(36) NOT NULL,
    account_id CHAR(36) NOT NULL,
    booking_time TIMESTAMP(6) NOT NULL,
    direction VARCHAR(16) NOT NULL,
    amount DECIMAL(19,4) NOT NULL,
    currency CHAR(3) NOT NULL,
    category_code VARCHAR(40) NOT NULL,
    merchant_name VARCHAR(120) NOT NULL,
    description VARCHAR(200) NOT NULL,
    counterparty_masked VARCHAR(80) NULL,
    status VARCHAR(24) NOT NULL,
    balance_after DECIMAL(19,4) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_transaction_account_time (account_id, booking_time),
    KEY idx_transaction_account_category_time (account_id, category_code, booking_time),
    CONSTRAINT fk_transaction_account FOREIGN KEY (account_id) REFERENCES account(id),
    CONSTRAINT chk_transaction_direction CHECK (direction IN ('IN', 'OUT')),
    CONSTRAINT chk_transaction_status CHECK (status IN ('POSTED', 'REVERSED')),
    CONSTRAINT chk_transaction_amount CHECK (amount > 0)
) ENGINE=InnoDB;

CREATE TABLE subscription (
    id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    charge_account_id CHAR(36) NOT NULL,
    merchant_name VARCHAR(120) NOT NULL,
    service_name VARCHAR(120) NOT NULL,
    amount DECIMAL(19,4) NOT NULL,
    currency CHAR(3) NOT NULL,
    billing_cycle VARCHAR(24) NOT NULL,
    next_charge_date DATE NULL,
    status VARCHAR(24) NOT NULL,
    detected_from VARCHAR(40) NOT NULL,
    cancellation_effect VARCHAR(200) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_subscription_owner_status (user_id, status),
    CONSTRAINT fk_subscription_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_subscription_account FOREIGN KEY (charge_account_id) REFERENCES account(id),
    CONSTRAINT chk_subscription_cycle CHECK (billing_cycle IN ('WEEKLY', 'MONTHLY', 'QUARTERLY', 'YEARLY')),
    CONSTRAINT chk_subscription_status CHECK (status IN ('ACTIVE', 'PAUSED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT chk_subscription_amount CHECK (amount > 0)
) ENGINE=InnoDB;

CREATE TABLE wealth_product (
    id CHAR(36) NOT NULL,
    product_code VARCHAR(40) NOT NULL,
    name VARCHAR(120) NOT NULL,
    product_type VARCHAR(32) NOT NULL,
    risk_level VARCHAR(8) NOT NULL,
    currency CHAR(3) NOT NULL,
    min_purchase DECIMAL(19,4) NOT NULL,
    increment_amount DECIMAL(19,4) NOT NULL,
    expected_yield_text VARCHAR(160) NOT NULL,
    term_days INT NOT NULL,
    sale_status VARCHAR(24) NOT NULL,
    valid_from DATE NOT NULL,
    valid_to DATE NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_wealth_product_code (product_code),
    KEY idx_wealth_product_sale_risk (sale_status, risk_level),
    CONSTRAINT chk_wealth_product_type CHECK (product_type IN ('DEPOSIT', 'BOND', 'FUND', 'STRUCTURED')),
    CONSTRAINT chk_wealth_product_risk CHECK (risk_level IN ('R1', 'R2', 'R3', 'R4', 'R5')),
    CONSTRAINT chk_wealth_product_status CHECK (sale_status IN ('ON_SALE', 'SUSPENDED', 'ENDED')),
    CONSTRAINT chk_wealth_product_amount CHECK (min_purchase >= 0 AND increment_amount > 0),
    CONSTRAINT chk_wealth_product_dates CHECK (valid_to >= valid_from)
) ENGINE=InnoDB;
