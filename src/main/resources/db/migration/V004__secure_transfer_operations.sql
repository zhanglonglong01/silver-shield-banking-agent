CREATE TABLE operation_request (
    id CHAR(36) NOT NULL,
    request_id CHAR(36) NOT NULL,
    conversation_id CHAR(36) NULL,
    user_id CHAR(36) NOT NULL,
    tool_name VARCHAR(128) NOT NULL,
    tool_version VARCHAR(32) NOT NULL,
    canonical_args_json LONGTEXT NOT NULL,
    args_hash VARCHAR(64) NOT NULL,
    display_summary_json LONGTEXT NOT NULL,
    summary_hash VARCHAR(64) NOT NULL,
    required_aal VARCHAR(8) NOT NULL,
    status VARCHAR(32) NOT NULL,
    idempotency_key_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    result_ref_type VARCHAR(40) NULL,
    result_ref_id CHAR(36) NULL,
    failure_code VARCHAR(64) NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_operation_owner_time (user_id, created_at),
    KEY idx_operation_owner_status (user_id, status),
    CONSTRAINT fk_operation_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT chk_operation_args_json CHECK (JSON_VALID(canonical_args_json)),
    CONSTRAINT chk_operation_summary_json CHECK (JSON_VALID(display_summary_json)),
    CONSTRAINT chk_operation_aal CHECK (required_aal IN ('AAL1', 'AAL2')),
    CONSTRAINT chk_operation_status CHECK (status IN (
        'AWAITING_STEP_UP', 'AWAITING_CONFIRMATION', 'EXECUTING',
        'SUCCEEDED', 'DENIED', 'FAILED', 'EXPIRED', 'CANCELLED'))
) ENGINE=InnoDB;

CREATE TABLE confirmation_challenge (
    id CHAR(36) NOT NULL,
    operation_id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    status VARCHAR(24) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    consumed_at TIMESTAMP(6) NULL,
    created_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_confirmation_operation (operation_id),
    KEY idx_confirmation_owner_status (user_id, status),
    CONSTRAINT fk_confirmation_operation FOREIGN KEY (operation_id) REFERENCES operation_request(id),
    CONSTRAINT fk_confirmation_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT chk_confirmation_status CHECK (status IN ('PENDING', 'CONSUMED', 'EXPIRED', 'CANCELLED'))
) ENGINE=InnoDB;

CREATE TABLE risk_decision (
    id CHAR(36) NOT NULL,
    operation_id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    evaluation_phase VARCHAR(24) NOT NULL,
    outcome VARCHAR(24) NOT NULL,
    policy_version VARCHAR(64) NOT NULL,
    input_hash VARCHAR(64) NOT NULL,
    reason_codes_json LONGTEXT NOT NULL,
    safe_explanation VARCHAR(500) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_risk_operation_phase (operation_id, evaluation_phase),
    CONSTRAINT fk_risk_operation FOREIGN KEY (operation_id) REFERENCES operation_request(id),
    CONSTRAINT fk_risk_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT chk_risk_reasons_json CHECK (JSON_VALID(reason_codes_json)),
    CONSTRAINT chk_risk_phase CHECK (evaluation_phase IN ('PRE_CONFIRM', 'FINAL_GUARD')),
    CONSTRAINT chk_risk_outcome CHECK (outcome IN ('ALLOW', 'REQUIRE_CONFIRMATION', 'REQUIRE_STEP_UP', 'DENY'))
) ENGINE=InnoDB;

CREATE TABLE idempotency_record (
    id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    scope VARCHAR(64) NOT NULL,
    idempotency_key_hash VARCHAR(64) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    operation_id CHAR(36) NOT NULL,
    status VARCHAR(24) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_idempotency_owner_scope_key (user_id, scope, idempotency_key_hash),
    CONSTRAINT fk_idempotency_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_idempotency_operation FOREIGN KEY (operation_id) REFERENCES operation_request(id),
    CONSTRAINT chk_idempotency_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'DENIED', 'FAILED'))
) ENGINE=InnoDB;

CREATE TABLE transfer_order (
    id CHAR(36) NOT NULL,
    operation_id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    source_account_id CHAR(36) NOT NULL,
    payee_id CHAR(36) NOT NULL,
    amount DECIMAL(19,4) NOT NULL,
    fee DECIMAL(19,4) NOT NULL,
    currency CHAR(3) NOT NULL,
    purpose VARCHAR(120) NULL,
    status VARCHAR(24) NOT NULL,
    source_balance_before DECIMAL(19,4) NOT NULL,
    source_balance_after DECIMAL(19,4) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    completed_at TIMESTAMP(6) NULL,
    failure_code VARCHAR(64) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_transfer_operation (operation_id),
    KEY idx_transfer_source_time (source_account_id, created_at),
    KEY idx_transfer_owner_time (user_id, created_at),
    CONSTRAINT fk_transfer_operation FOREIGN KEY (operation_id) REFERENCES operation_request(id),
    CONSTRAINT fk_transfer_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_transfer_source FOREIGN KEY (source_account_id) REFERENCES account(id),
    CONSTRAINT fk_transfer_payee FOREIGN KEY (payee_id) REFERENCES payee(id),
    CONSTRAINT chk_transfer_status CHECK (status IN ('SUCCEEDED', 'FAILED')),
    CONSTRAINT chk_transfer_amount CHECK (amount > 0 AND fee >= 0)
) ENGINE=InnoDB;

CREATE TABLE operation_audit (
    id CHAR(36) NOT NULL,
    operation_id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    stage VARCHAR(32) NOT NULL,
    outcome VARCHAR(32) NOT NULL,
    reason_code VARCHAR(64) NOT NULL,
    safe_explanation VARCHAR(500) NOT NULL,
    occurred_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_operation_audit_operation_time (operation_id, occurred_at),
    KEY idx_operation_audit_owner_time (user_id, occurred_at),
    CONSTRAINT fk_operation_audit_operation FOREIGN KEY (operation_id) REFERENCES operation_request(id),
    CONSTRAINT fk_operation_audit_user FOREIGN KEY (user_id) REFERENCES app_user(id)
) ENGINE=InnoDB;
